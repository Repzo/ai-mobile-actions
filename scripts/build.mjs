#!/usr/bin/env node
// Builds the contract from actions/*.yaml and checks it on the way:
//   catalog.json              the language-neutral catalog every client reads
//   src/generated/catalog.ts  the same catalog as a TypeScript constant
//   src/generated/types.ts    TypeScript types for every action's params and result
//   README.md                 the action table between the `actions` markers
// `--check` writes nothing and fails when any of them is out of date.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import { compile } from "json-schema-to-typescript";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const GENERATED_NOTE = "Generated by scripts/build.mjs from actions/*.yaml — do not edit.";

let failures = 0;
const fail = (message) => {
  failures += 1;
  console.error(`✗ ${message}`);
};

const readText = (path) => readFileSync(join(ROOT, path), "utf8");
const readJson = (path) => JSON.parse(readText(path));
const readYaml = (path) => YAML.parse(readText(path)) ?? {};

const pkg = readJson("package.json");

/** -1, 0 or 1, comparing two x.y.z versions. */
const compareVersions = (a, b) => {
  const left = a.split(".").map(Number);
  const right = b.split(".").map(Number);
  for (let i = 0; i < 3; i += 1) {
    if (left[i] !== right[i]) return left[i] < right[i] ? -1 : 1;
  }
  return 0;
};

// ── validators ──────────────────────────────────────────────────────────────
// Strict, except that `required` may name properties declared next to it rather than in the
// same subschema — how anyOf / if-then branches are usually written.
const ajv = new Ajv({ strict: true, strictRequired: false, allErrors: true, allowUnionTypes: true });
addFormats(ajv);
const requestSchema = readJson("schemas/action-request.schema.json");
const resultSchema = readJson("schemas/action-result.schema.json");
ajv.addSchema(requestSchema);
ajv.addSchema(resultSchema);
const validateDefinition = ajv.compile(readJson("schemas/action-definition.schema.json"));

// ── shared fragments ────────────────────────────────────────────────────────
const shared = readYaml("actions/_shared.yaml");
const base = readYaml("actions/_catalog.yaml");

/** Replaces every `{ $shared: name }` with a copy of that fragment. */
const inlineShared = (node, where) => {
  if (Array.isArray(node)) return node.map((item) => inlineShared(item, where));
  if (!node || typeof node !== "object") return node;
  if ("$shared" in node) {
    const fragment = shared[node.$shared];
    if (!fragment) {
      fail(`${where}: unknown shared fragment '${node.$shared}'`);
      return {};
    }
    return inlineShared(structuredClone(fragment), where);
  }
  return Object.fromEntries(
    Object.entries(node).map(([key, value]) => [key, inlineShared(value, where)]),
  );
};

// ── actions ─────────────────────────────────────────────────────────────────
const files = readdirSync(join(ROOT, "actions"))
  .filter((file) => file.endsWith(".yaml") && !file.startsWith("_"))
  .sort();

const actions = [];
for (const file of files) {
  const where = `actions/${file}`;
  const raw = readYaml(where);
  if (!validateDefinition(raw)) {
    fail(`${where}: ${ajv.errorsText(validateDefinition.errors, { dataVar: "action" })}`);
    continue;
  }
  if (basename(file, ".yaml") !== raw.name) {
    fail(`${where}: the file must be named after the action (${raw.name}.yaml)`);
  }
  if (compareVersions(raw.since, pkg.version) > 0) {
    fail(`${where}: since ${raw.since} is newer than the package version ${pkg.version}`);
  }

  const params = inlineShared(raw.params, `${where} params`);
  const result = raw.result ? inlineShared(raw.result, `${where} result`) : undefined;
  let validateParams;
  let validateData;
  try {
    validateParams = ajv.compile(params);
    validateData = result ? ajv.compile(result) : undefined;
  } catch (error) {
    fail(`${where}: ${error.message}`);
    continue;
  }

  const errorCodes = new Set((raw.errors ?? []).map((item) => item.code));
  raw.examples.forEach((example, index) => {
    const at = `${where} examples[${index}]`;
    if (example.request.action !== raw.name) fail(`${at}: request.action must be ${raw.name}`);
    if (!validateParams(example.request.params)) {
      fail(`${at}: params: ${ajv.errorsText(validateParams.errors, { dataVar: "params" })}`);
    }
    const answer = example.result;
    if (!answer) return;
    if (answer.action !== raw.name) fail(`${at}: result.action must be ${raw.name}`);
    if (answer.status === "success") {
      if (!validateData) fail(`${at}: ${raw.name} does not report a result, so no success example`);
      else if (!validateData(answer.data ?? {})) {
        fail(`${at}: data: ${ajv.errorsText(validateData.errors, { dataVar: "data" })}`);
      }
    }
    if (answer.status === "failed" && !errorCodes.has(answer.data?.code)) {
      fail(`${at}: failure code '${answer.data?.code}' is not one of the action's errors`);
    }
  });

  actions.push({
    name: raw.name,
    title: raw.title,
    summary: raw.summary,
    description: raw.description,
    since: raw.since,
    ...(raw.deprecated ? { deprecated: raw.deprecated } : {}),
    reports_result: raw.reports_result,
    params,
    ...(result ? { result } : {}),
    errors: raw.errors ?? [],
    examples: raw.examples,
  });
}

if (!Array.isArray(base.guidance) || base.guidance.some((line) => typeof line !== "string")) {
  fail("actions/_catalog.yaml: guidance must be a list of strings");
}
const text = base.transport?.text;
if (!text?.request_block || !text?.result_prefix || !text?.instructions) {
  fail("actions/_catalog.yaml: transport.text needs request_block, result_prefix and instructions");
}

if (failures) {
  console.error(`\n${failures} problem(s) — nothing written.`);
  process.exit(1);
}

const catalog = {
  name: pkg.name,
  version: pkg.version,
  guidance: base.guidance,
  transport: base.transport,
  actions,
};

// ── outputs ─────────────────────────────────────────────────────────────────
const pascal = (name) => name.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

// Plain arrays (min/max items stay in the schema), formatted output, and closed objects
// unless a result schema leaves them open.
const TS_OPTIONS = {
  bannerComment: "",
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  format: true,
};
/**
 * The schema without its validation-only branches — `anyOf` / `oneOf` / `allOf` entries that
 * only list `required` properties, and `if` / `then` / `else` — which TypeScript can't express
 * and would otherwise widen the type to "anything". The catalog keeps them for validation.
 */
const forTypes = (node) => {
  if (Array.isArray(node)) return node.map(forTypes);
  if (!node || typeof node !== "object") return node;
  const onlyRequired = (branch) =>
    branch && typeof branch === "object" && Object.keys(branch).every((key) => key === "required");
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (["if", "then", "else"].includes(key)) continue;
    if (["anyOf", "oneOf", "allOf"].includes(key) && Array.isArray(value) && value.every(onlyRequired)) {
      continue;
    }
    out[key] = forTypes(value);
  }
  return out;
};

const typeChunks = [];
for (const action of actions) {
  const type = pascal(action.name);
  typeChunks.push(
    await compile(forTypes(action.params), `${type}Params`, TS_OPTIONS),
  );
  if (action.result) {
    typeChunks.push(
      await compile(forTypes(action.result), `${type}Result`, {
        ...TS_OPTIONS,
        additionalProperties: true,
      }),
    );
  }
}
const typesTs = [
  `// ${GENERATED_NOTE}`,
  "",
  `export type ActionName = ${actions.map((action) => JSON.stringify(action.name)).join(" | ")};`,
  "",
  ...typeChunks.map((chunk) => chunk.trim() + "\n"),
  "/** Each action's `params`. */",
  "export interface ActionParams {",
  ...actions.map((action) => `  ${action.name}: ${pascal(action.name)}Params;`),
  "}",
  "",
  "/** Each action's `data` in a successful result (`never`: the phone reports no success). */",
  "export interface ActionResultData {",
  ...actions.map(
    (action) => `  ${action.name}: ${action.result ? `${pascal(action.name)}Result` : "never"};`,
  ),
  "}",
  "",
].join("\n");

const catalogTs = [
  `// ${GENERATED_NOTE}`,
  'import type { MobileActionsCatalog } from "../types.js";',
  "",
  `export const CATALOG: MobileActionsCatalog = ${JSON.stringify(catalog, null, 2)};`,
  "",
].join("\n");

const catalogJson = `${JSON.stringify(catalog, null, 2)}\n`;

const cell = (value) => String(value).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const table = [
  "| Action | What it does | Reports a result | Since |",
  "| --- | --- | --- | --- |",
  ...actions.map(
    (action) =>
      `| [\`${action.name}\`](actions/${action.name}.yaml) | ${cell(action.summary)} | ${
        action.reports_result ? "yes" : "no"
      } | ${action.since} |`,
  ),
].join("\n");
const readme = readText("README.md");
const START = "<!-- actions:start -->";
const END = "<!-- actions:end -->";
if (!readme.includes(START) || !readme.includes(END)) {
  fail(`README.md: the ${START} / ${END} markers are missing`);
  process.exit(1);
}
const readmeOut =
  readme.slice(0, readme.indexOf(START) + START.length) +
  `\n${table}\n` +
  readme.slice(readme.indexOf(END));

const outputs = {
  "catalog.json": catalogJson,
  "src/generated/catalog.ts": catalogTs,
  "src/generated/types.ts": typesTs,
  "README.md": readmeOut,
};

if (CHECK) {
  const stale = Object.entries(outputs)
    .filter(([path, content]) => {
      try {
        return readText(path) !== content;
      } catch {
        return true;
      }
    })
    .map(([path]) => path);
  if (stale.length) {
    console.error(`✗ out of date: ${stale.join(", ")} — run \`npm run generate\` and commit the result.`);
    process.exit(1);
  }
  console.log(`✓ ${actions.length} actions valid; generated files up to date.`);
} else {
  mkdirSync(join(ROOT, "src/generated"), { recursive: true });
  for (const [path, content] of Object.entries(outputs)) writeFileSync(join(ROOT, path), content);
  console.log(`✓ ${actions.length} actions → ${Object.keys(outputs).join(", ")}`);
}
